from __future__ import annotations

import json
import os
import sys
import subprocess
from pathlib import Path

from google import genai
from google.genai import types


ROOT = Path(__file__).resolve().parents[1]

API_KEY = os.environ.get("GEMINI_API_KEY")
MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.6-flash")

# ============================================================
# FOUR-LAYER AGENT CONTEXT
# ============================================================

MASTER_DOCUMENT_FILE = (
    ROOT / "docs/PYHOK_MASTER_ARCHITECTURE.md"
)

CONSTITUTION_FILE = (
    ROOT / "prompts/00_agent_constitution.system.txt"
)

CURRENT_KNOWLEDGE_FILE = (
    ROOT / "generator/input/current_knowledge_context.json"
)

EVOLUTION_POLICY_FILE = (
    ROOT / "evolution/evolution-policy.json"
)

# Compatibility/context artifact generated by the repository.
AGENT_CONTEXT_FILE = (
    ROOT / "generator/input/agent_context.json"
)

# Auditor-specific instructions.
AUDITOR_PROMPT_FILE = (
    ROOT / "prompts/01_graph_auditor.system.txt"
)

OUTPUT_FILE = (
    ROOT / "generator/output/audit.json"
)


# ============================================================
# FILE HELPERS
# ============================================================

def read_text(path: Path) -> str:
    if not path.exists():
        raise SystemExit(
            f"Required file not found: {path}"
        )

    return path.read_text(
        encoding="utf-8"
    )


def read_json(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(
            f"Required JSON file not found: {path}"
        )

    try:
        return json.loads(
            path.read_text(
                encoding="utf-8"
            )
        )
    except json.JSONDecodeError as exc:
        raise SystemExit(
            f"Invalid JSON in {path}: {exc}"
        )


# ============================================================
# CONTEXT GENERATION
# ============================================================

def build_context() -> None:
    """
    Always regenerate the repository-derived context before
    auditing.

    The current knowledge context must represent the actual
    repository state at the moment of the audit.
    """

    print("Building current repository context...")

    result = subprocess.run(
        [
            sys.executable,
            str(
                ROOT /
                "generator/build_agent_context.py"
            )
        ],
        cwd=ROOT,
        capture_output=True,
        text=True
    )

    if result.stdout:
        print(result.stdout)

    if result.returncode != 0:
        if result.stderr:
            print(result.stderr)

        raise SystemExit(
            "Failed to build agent context."
        )


# ============================================================
# FOUR-LAYER CONTEXT
# ============================================================

def build_four_layer_context() -> str:
    """
    Assemble the four epistemic layers used by the agent.

    Layer 1:
        Master Document
        Defines what PyHok is and what the architecture means.

    Layer 2:
        Agent Constitution
        Defines how the agent must reason.

    Layer 3:
        Current Knowledge Context
        Defines what actually exists in the repository now.

    Layer 4:
        Evolution Policy
        Defines what the agent is authorized to propose.

    IMPORTANT:
        The Master Document is NOT evidence that an entity exists.
        Only the Current Knowledge Context establishes current
        repository state.
    """

    master_document = read_text(
        MASTER_DOCUMENT_FILE
    )

    constitution = read_text(
        CONSTITUTION_FILE
    )

    current_knowledge = read_json(
        CURRENT_KNOWLEDGE_FILE
    )

    evolution_policy = read_json(
        EVOLUTION_POLICY_FILE
    )

    context = f"""
================================================================
PYHOK KNOWLEDGE AGENT — FOUR-LAYER CONTEXT
================================================================

IMPORTANT EPISTEMIC RULE:

The following four layers have different authorities.

LAYER 1 — MASTER DOCUMENT
Purpose:
Define what PyHok is, its architecture, goals, concepts,
terminology and intended system behavior.

The Master Document explains the TARGET ARCHITECTURE.

It MUST NOT be interpreted as proof that a signal, method,
question, relation, sensor or runtime capability currently exists.

If something is described in the Master Document but absent
from the Current Knowledge Context, it is NOT currently
available to the Knowledge Graph.

---------------------------------------------------------------

LAYER 2 — AGENT CONSTITUTION
Purpose:
Define how the agent must reason, what epistemic discipline
it must follow, and what kinds of reasoning are forbidden.

The Constitution governs the agent's reasoning process.

---------------------------------------------------------------

LAYER 3 — CURRENT KNOWLEDGE CONTEXT
Purpose:
Represent the actual repository state available during this run.

THIS IS THE AUTHORITATIVE SOURCE FOR WHAT CURRENTLY EXISTS.

Only entities explicitly present here may be treated as existing.

Anything absent must be treated as UNKNOWN.

Do not infer existence from the Master Document.

---------------------------------------------------------------

LAYER 4 — EVOLUTION POLICY
Purpose:
Define what the agent is authorized to propose and the limits
that apply to evolution.

The Policy governs authorization.

---------------------------------------------------------------

AUTHORITY ORDER

For architectural meaning:
    Master Document

For reasoning behavior:
    Agent Constitution

For current existence:
    Current Knowledge Context

For authorization:
    Evolution Policy

When these layers appear to conflict, preserve their separation.
Do not silently merge them.

================================================================
LAYER 1 — MASTER DOCUMENT
================================================================

{master_document}

================================================================
LAYER 2 — AGENT CONSTITUTION
================================================================

{constitution}

================================================================
LAYER 3 — CURRENT KNOWLEDGE CONTEXT
================================================================

{json.dumps(
    current_knowledge,
    ensure_ascii=False,
    indent=2
)}

================================================================
LAYER 4 — EVOLUTION POLICY
================================================================

{json.dumps(
    evolution_policy,
    ensure_ascii=False,
    indent=2
)}

================================================================
END FOUR-LAYER CONTEXT
================================================================
"""

    return context


