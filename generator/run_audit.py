# ============================================================
# MAIN
# ============================================================

def main() -> None:

    if not API_KEY:
        raise SystemExit(
            "GEMINI_API_KEY is missing."
        )

    # Always rebuild the repository-derived context.
    build_context()

    # Make sure the generated current context exists.
    if not CURRENT_KNOWLEDGE_FILE.exists():
        raise SystemExit(
            "Current knowledge context was not generated."
        )

    auditor_prompt = read_text(
        AUDITOR_PROMPT_FILE
    )

    four_layer_context = (
        build_four_layer_context()
    )

    user_prompt = f"""
You are now performing an epistemic audit of the PyHok
Knowledge Graph.

Your task is NOT to create knowledge.

Your task is to inspect the four-layer context and identify
only defensible opportunities for evolution.

The Master Document tells you what PyHok IS and what the
architecture is intended to accomplish.

The Current Knowledge Context tells you what ACTUALLY EXISTS.

The Agent Constitution tells you HOW TO THINK.

The Evolution Policy tells you WHAT YOU ARE AUTHORIZED TO PROPOSE.

CRITICAL RULE:

Never treat an architectural capability described by the
Master Document as an existing capability unless it is also
present in the Current Knowledge Context.

For example:

If the Master Document describes an eye-tracking signal,
but Current Knowledge contains no eye-tracking signal,
then eye-tracking is UNKNOWN/UNAVAILABLE for the current graph.

You may identify the absence as an architectural gap if the
Constitution and Policy permit identifying such a gap.

You may NOT invent the missing signal.

You may NOT invent a method for evaluating it.

You may NOT invent a QuestionEntity that depends on it.

You may NOT fabricate evidence.

A useful opportunity must therefore be grounded in what the
repository can actually support.

The most important objective is NOT to maximize the number of
opportunities.

The objective is to find opportunities that meaningfully
improve the Knowledge Graph and ultimately help the system
represent observable patterns relevant to PyHok.

A proposal that is technically valid but conceptually trivial,
redundant, unsupported, or disconnected from meaningful
observational reasoning is NOT useful.

Likewise, if the current graph does not contain enough
observable infrastructure to support a defensible evolution,
you must abstain.

Do not generate an opportunity merely because the graph is
small.

Do not generate an opportunity merely because a mission domain
has zero questions.

Do not generate an opportunity merely to make the system
appear to evolve.

At most three opportunities may be returned.

Return JSON only.

================================================================
AUDITOR-SPECIFIC INSTRUCTIONS
================================================================

{auditor_prompt}

================================================================
FOUR-LAYER CONTEXT
================================================================

{four_layer_context}

================================================================
END INPUT
================================================================
"""

    client = genai.Client(
        api_key=API_KEY
    )

    response = client.models.generate_content(
        model=MODEL,
        contents=user_prompt,
        config=types.GenerateContentConfig(
            system_instruction=auditor_prompt,
            response_mime_type="application/json",
            response_schema=RESPONSE_SCHEMA
        )
    )

    if not response.text:
        raise SystemExit(
            "Gemini returned an empty response."
        )

    try:
        result = json.loads(
            response.text
        )
    except json.JSONDecodeError as exc:
        print(response.text)
        raise SystemExit(
            f"Gemini returned invalid JSON: {exc}"
        )

    OUTPUT_FILE.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    OUTPUT_FILE.write_text(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2
        ) + "\n",
        encoding="utf-8"
    )

    print("=== AUDIT RESULT ===")
    print(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2
        )
    )


if __name__ == "__main__":
    main()
